-- ----------------------------------------------------------------------------
-- Контрольные запросы (после загрузки данных)
-- ----------------------------------------------------------------------------

-- 1) Количество строк в таблицах
SELECT 'branches'         AS tbl, COUNT(*) AS cnt FROM dbo.branches
UNION ALL SELECT 'membership_types', COUNT(*) FROM dbo.membership_types
UNION ALL SELECT 'clients',          COUNT(*) FROM dbo.clients
UNION ALL SELECT 'memberships',      COUNT(*) FROM dbo.memberships
UNION ALL SELECT 'payments',         COUNT(*) FROM dbo.payments;
GO

-- 2) NULL-контроль
SELECT
    SUM(CASE WHEN email      IS NULL THEN 1 ELSE 0 END) AS clients_no_email,
    SUM(CASE WHEN birth_date IS NULL THEN 1 ELSE 0 END) AS clients_no_birth
FROM dbo.clients;
GO

-- 3) Один платёж на абонемент и совпадение сумм с price_paid
--    (для CANCELLED-абонемента проверяется только количество платежей).
--    Должно вернуть 0 строк.
SELECT m.id AS membership_id, m.status, m.price_paid,
       COUNT(p.id) AS pay_cnt,
       ISNULL(SUM(CASE WHEN p.status='PAID' THEN p.amount END),0) AS paid_sum
FROM dbo.memberships m
         LEFT JOIN dbo.payments p ON p.membership_id = m.id
GROUP BY m.id, m.status, m.price_paid
HAVING COUNT(p.id) <> 1
    OR (m.status <> 'CANCELLED'
    AND ISNULL(SUM(CASE WHEN p.status='PAID' THEN p.amount END),0) <> m.price_paid);
GO

-- 4) Платежи в будущем — должно вернуть 0 строк
SELECT id, paid_at
FROM dbo.payments
WHERE paid_at > CAST('2026-10-06' AS DATETIME2);
GO

-- 5) ACTIVE/FROZEN с истёкшим end_date — должно вернуть 0 строк
SELECT id, status, end_date
FROM dbo.memberships
WHERE status IN ('ACTIVE','FROZEN') AND end_date < CAST('2026-10-06' AS DATE);
GO

-- 6) Итоги PAID по филиалам — используйте результат для порога HAVING
SELECT b.code, b.name,
       COUNT(p.id)   AS paid_cnt,
       SUM(p.amount) AS paid_total
FROM dbo.payments p
         JOIN dbo.branches b ON b.id = p.branch_id
WHERE p.status = 'PAID'
GROUP BY b.code, b.name
ORDER BY b.code;
