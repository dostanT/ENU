import SwiftUI

@main
struct FitnessCRMApp: App {
    
    private let appContainer: AppContainer
    
    init() {
        let client = SupabaseManager.shared.client
        let authProtocol = SupabaseAuthRepository(client: client)
        appContainer = AppContainer(authRepository: authProtocol)
    }
    
    var body: some Scene {
        WindowGroup {
            RootView(appContainer: appContainer)
        }
    }
}
